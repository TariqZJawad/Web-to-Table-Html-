import numpy as np
from qutip import *

# --- 1. تعريف المتغيرات الفيزيائية ---
omega = 1.0   # تردد الكيوبتات (نفرض أن الشاحن والبطارية متطابقان)
zeta = 0.1    # قوة التفاعل (سرعة تبادل الطاقة بين الشاحن والبطارية)

# --- 2. تجهيز المصفوفات الأساسية ---
sz = sigmaz()  # مصفوفة الطاقة
sp = sigmap()  # مؤثر الرفع (يكتسب طاقة)
sm = sigmam()  # مؤثر الهبوط (يفقد طاقة)
I = qeye(2)    # مصفوفة الوحدة (Identity) - تعني "لا تفعل شيئاً لهذا الكيوبت"

# --- 3. دمج الكيوبتات باستخدام دالة الجداء الموتري (tensor) ---
# الشاحن (الكيوبت الأول): نضع المؤثر في الخانة الأولى، ومصفوفة الوحدة في الثانية
sz1 = tensor(sz, I)
sp1 = tensor(sp, I)
sm1 = tensor(sm, I)

# البطارية (الكيوبت الثاني): نضع مصفوفة الوحدة في الخانة الأولى، والمؤثر في الثانية
sz2 = tensor(I, sz)
sp2 = tensor(I, sp)
sm2 = tensor(I, sm)

# --- 4. بناء الهاميلتونيان الكلي ---
# الطاقة الداخلية للشاحن والبطارية
H0 = 0.5 * omega * sz1 + 0.5 * omega * sz2

# تفاعل تبادل الطاقة (Hopping Interaction)
H_int = zeta * (sp1 * sm2 + sm1 * sp2)

# الهاميلتونيان الكلي
H_total = H0 + H_int

print("=== Total Hamiltonian (4x4 Matrix) ===")
print(H_total)
